-- Chạy trong Supabase SQL Editor.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_id text unique not null,
  service text not null check (service in ('movie','drink','shopee')),
  status text not null default 'new' check (status in ('new','checking','confirmed','completed','cancelled')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
-- Không tạo policy public: khách truy cập không được đọc danh sách đơn.
